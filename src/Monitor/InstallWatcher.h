#pragma once

#include <string>

namespace GuardDog {

struct Config;

// 安装拦截（模块 C 的扩展）。
//
// 为什么需要它：进程监控只能拦住"已经装好并开始运行"的程序。用户想要的
// "阻止安装"是另一件事——安装过程会把文件铺到 Program Files、AppData 等位置，
// 等装完再清理，用户已经看到"安装成功"了。
//
// 实现取向：不做文件系统过滤驱动（纯用户态做不到，也不需要），而是
// 监视常见安装根目录下**新建的目录名**，与黑名单规则的名称/路径匹配。
// 命中即延迟数秒整体清理——延迟是为了让安装程序先把文件写完，
// 否则文件处于独占写入状态，删不干净反而留下残骸。
//
// 为什么用轮询而不是 ReadDirectoryChangesW：安装过程本身要持续数秒到数十秒，
// 2 秒的发现延迟对这种场景完全够用；而目录变更通知需要处理缓冲区溢出、
// 句柄失效、多目录 IOCP 等一堆边界情况，复杂度远高于收益。
// 每次轮询只是枚举几十到几百个目录项，开销可忽略。
class InstallWatcher {
public:
    // 在服务主循环里周期调用（内部计时，默认 2 秒一轮）
    static void Poll(const Config& config);

    // 配置热重载后重建基线：规则变了，待清理队列里那些"当时判定为命中"的
    // 结论可能已经失效，必须清掉重新判定，避免用旧规则删除目录
    static void Reset();
};

} // namespace GuardDog